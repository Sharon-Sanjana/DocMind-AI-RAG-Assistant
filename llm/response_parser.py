"""
Response Parser

Cleans and validates responses
generated by the language model.
"""


class ResponseParser:
    """
    Parses LLM responses.
    """

    def clean(
        self,
        response: str,
    ) -> str:
        """
        Clean whitespace and formatting.
        """

        if not response:
            return (
                "The model returned an empty response."
            )

        response = response.strip()

        lines = [
            line.strip()
            for line in response.splitlines()
            if line.strip()
        ]

        return "\n".join(lines)

    def validate(
        self,
        response: str,
    ) -> bool:
        """
        Validate response.
        """

        return bool(response.strip())

    def parse(
        self,
        response: str,
    ) -> str:
        """
        Parse response.
        """

        cleaned = self.clean(
            response
        )

        if not self.validate(
            cleaned
        ):
            raise ValueError(
                "Invalid LLM response."
            )

        return cleaned